#!/usr/bin/env python3
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest


HOOK = Path(__file__).resolve().parents[1] / ".githooks" / "pre-commit"


class PreCommitTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
        self.git("init", "-q")
        self.git("config", "user.name", "Hook test")
        self.git("config", "user.email", "hook@example.invalid")
        self.git("config", "commit.gpgsign", "false")
        (self.root / ".githooks").mkdir()
        shutil.copy2(HOOK, self.root / ".githooks/pre-commit")
        self.git("config", "core.hooksPath", ".githooks")

    def git(self, *args, check=True):
        return subprocess.run(
            ["git", "--literal-pathspecs", *args], cwd=self.root, env=self.env,
            capture_output=True, text=True, check=check,
        )

    def stage(self, path, content):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        self.git("add", "--", path)

    def hook(self):
        return subprocess.run(
            [str(self.root / ".githooks/pre-commit")], cwd=self.root,
            env=self.env, capture_output=True, text=True,
        )

    def test_boundary_and_commit_rejection(self):
        self.stage("source.go", b"a" * 20_000)
        self.git("commit", "-qm", "boundary")
        self.stage("source.go", b"a" * 20_001)
        result = self.git("commit", "-qm", "oversized", check=False)
        self.assertNotEqual(result.returncode, 0)
        for expected in ("source.go", "20,001", "5,000.25", "Как разделить", "git add", "импорты"):
            self.assertIn(expected, result.stderr)

    def test_only_index_content_is_checked(self):
        (self.root / "untracked.go").write_bytes(b"x" * 30_000)
        self.stage("source.go", b"x" * 20_000)
        (self.root / "source.go").write_bytes(b"x" * 30_000)
        self.assertEqual(self.hook().returncode, 0)
        self.git("add", "source.go")
        (self.root / "source.go").write_bytes(b"small")
        self.assertNotEqual(self.hook().returncode, 0)

    def test_generated_files_and_lockfiles(self):
        for path in ("web/package-lock.json", "go.sum", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock",
                     "notes.md", "page.html", "image.png", "data.json", "app.js", "app.css", "secretary", "script.py"):
            self.stage(path, b"x" * 30_000)
        self.stage("generated.go", b"// Code generated by tool. DO NOT EDIT.\n" + b"x" * 30_000)
        self.stage("generated.sh", b"/* @generated */\n" + b"x" * 30_000)
        self.stage("web/Generated.svelte", b"x" * 30_000)
        self.stage(".gitattributes", b"/web/Generated.svelte linguist-generated=true\n")
        (self.root / ".gitattributes").write_text("")
        self.assertEqual(self.hook().returncode, 0)
        self.git("add", ".gitattributes")
        self.assertNotEqual(self.hook().returncode, 0)

    def test_deleted_and_unchanged_large_files_are_ignored(self):
        self.stage("legacy.go", b"x" * 30_000)
        self.stage("deleted.go", b"x" * 30_000)
        self.git("-c", "core.hooksPath=/dev/null", "commit", "-qm", "legacy")
        self.git("rm", "deleted.go")
        self.stage("small.go", b"small")
        self.assertEqual(self.hook().returncode, 0)

    def test_rename_and_unusual_paths(self):
        self.stage("original.go", b"x" * 30_000)
        self.git("-c", "core.hooksPath=/dev/null", "commit", "-qm", "legacy")
        self.git("mv", "original.go", "renamed.go")
        self.assertNotEqual(self.hook().returncode, 0)
        self.git("reset", "--hard", "-q")
        self.stage("-space ü\n[abc].go", "я".encode() * 10_001)
        result = self.hook()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("20,002", result.stderr)
        self.assertIn("[abc].go", result.stderr)

    def test_all_selected_extensions_are_checked(self):
        for path in ("source.go", "script.sh", "Component.svelte"):
            with self.subTest(path=path):
                self.stage(path, b"x" * 20_000)
                self.assertEqual(self.hook().returncode, 0)
                self.stage(path, b"x" * 20_001)
                self.assertNotEqual(self.hook().returncode, 0)
                self.git("rm", "-f", "--cached", "--", path)

    def test_symlink_is_ignored(self):
        os.symlink("missing-target", self.root / "link.go")
        self.git("add", "link.go")
        self.assertEqual(self.hook().returncode, 0)


if __name__ == "__main__":
    unittest.main()
